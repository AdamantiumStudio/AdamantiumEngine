using Adamantium.Imaging.Mq;
using NUnit.Framework;

namespace Adamantium.ImagingTests;

[TestFixture]
public class MqDecoderTests
{
    /// <summary>The test sequence of ITU-T T.88, H.2: 256 decisions in one context.</summary>
    [Test]
    public void StandardTestSequenceDecodes()
    {
        byte[] coded =
        [
            0x84, 0xC7, 0x3B, 0xFC, 0xE1, 0xA1, 0x43, 0x04, 0x02, 0x20, 0x00, 0x00, 0x41, 0x0D, 0xBB, 0x86, 0xF4, 0x31,
            0x7F, 0xFF, 0x88, 0xFF, 0x37, 0x47, 0x1A, 0xDB, 0x6A, 0xDF, 0xFF, 0xAC,
        ];
        byte[] expected =
        [
            0x00, 0x02, 0x00, 0x51, 0x00, 0x00, 0x00, 0xC0, 0x03, 0x52, 0x87, 0x2A, 0xAA, 0xAA, 0xAA, 0xAA, 0x82, 0xC0,
            0x20, 0x00, 0xFC, 0xD7, 0x9E, 0xF6, 0xBF, 0x7F, 0xED, 0x90, 0x4F, 0x46, 0xA3, 0xBF,
        ];
        var decoder = new MqDecoder(coded, 0, coded.Length);
        var contexts = new byte[1];
        var decoded = new byte[expected.Length];
        for (var i = 0; i < expected.Length * 8; i++)
        {
            decoded[i / 8] |= (byte)(decoder.Decode(contexts, 0) << (7 - i % 8));
        }

        Assert.That(decoded, Is.EqualTo(expected));
    }
}
