using System.Security;
using System.Text;
using Adamantium.Core;

namespace Adamantium.Wayland.Generator;

/// <summary>Writes C# for the protocols: a class per interface, and the wl_interface tables libwayland reads.</summary>
public sealed class CSharpEmitter
{
    private const string Namespace = "Adamantium.Wayland";

    private static readonly HashSet<string> BaseMembers =
    [
        "Handle", "Version", "Id", "DestroyProxy", "Interface", "InterfaceName", "InterfaceVersion", "Create",
        "Adopt", "Find", "Marshal", "MarshalDestroy", "DispatchEvent", "Equals", "GetHashCode", "ToString",
        "GetType", "MemberwiseClone", "Finalize",
    ];

    private readonly IReadOnlyList<Protocol> protocols;
    private readonly Dictionary<string, Interface> interfaces;

    public CSharpEmitter(IReadOnlyList<Protocol> protocols)
    {
        this.protocols = protocols;
        interfaces = protocols.SelectMany(p => p.Interfaces).ToDictionary(i => i.Name);
    }

    private static void Header(TextGenerator w, string source, string copyright)
    {
        w.WriteLine("// ----------------------------------------------------------------------------------------------");
        w.WriteLine("// <auto-generated>");
        w.WriteLine("// This file was generated by Adamantium.Wayland.Generator" + (source == null ? "." : $" from {source}."));
        w.WriteLine("// Do not edit this file manually because you will lose all your changes after the next generation.");
        w.WriteLine("// </auto-generated>");
        w.WriteLine("// ----------------------------------------------------------------------------------------------");

        if (!string.IsNullOrWhiteSpace(copyright))
        {
            w.WriteLine("//");
            w.WriteLine("// The protocol it is generated from, and the documentation taken from it:");
            w.WriteLine("//");
            foreach (var line in Dedent(copyright))
            {
                w.WriteLine(line.Length == 0 ? "//" : "// " + line);
            }
        }

        w.NewLine();
    }

    public string Protocol(Protocol protocol)
    {
        var w = new TextGenerator();
        Header(w, protocol.FileName, protocol.Copyright);
        w.WriteLine("using System;");
        w.NewLine();
        w.WriteLine($"namespace {Namespace};");

        foreach (var @interface in protocol.Interfaces)
        {
            w.NewLine();
            Interface(w, @interface);
        }

        return w.ToString();
    }

    public string Interfaces()
    {
        var w = new TextGenerator();
        Header(w, null, null);
        w.WriteLine($"namespace {Namespace};");
        w.NewLine();
        w.WriteLine("/// <summary>The wl_interface of every interface of the generated protocols: names, versions and the");
        w.WriteLine("/// signatures libwayland marshals requests and reads events by.</summary>");
        w.WriteLine("public static unsafe partial class WaylandInterfaces");
        w.WriteOpenBraceAndIndent();

        var all = protocols.SelectMany(p => p.Interfaces).ToList();
        foreach (var i in all)
        {
            w.WriteLine($"public static readonly WlInterface* {Naming.Pascal(i.Name)} = WaylandInterfaceBuilder.Allocate();");
        }

        w.NewLine();
        w.WriteLine("static WaylandInterfaces()");
        w.WriteOpenBraceAndIndent();
        foreach (var i in all)
        {
            w.WriteLine($"WaylandInterfaceBuilder.Fill({Naming.Pascal(i.Name)}, \"{i.Name}\", {i.Version},");
            w.PushIndent();
            Messages(w, i.Requests, ",");
            Messages(w, i.Events, ");");
            w.PopIndent();
        }

        w.UnindentAndWriteCloseBrace();
        w.UnindentAndWriteCloseBrace();
        return w.ToString();
    }

    private void Messages(TextGenerator w, IReadOnlyList<Message> messages, string end)
    {
        if (messages.Count == 0)
        {
            w.WriteLine("[]" + end);
            return;
        }

        w.WriteLine("[");
        w.PushIndent();
        foreach (var m in messages)
        {
            List<string> types = [];
            foreach (var a in m.Arguments)
            {
                if (a.Type == ArgumentType.NewId && a.Interface == null)
                {
                    types.AddRange(["null", "null", "null"]);
                }
                else if (a.Type is ArgumentType.Object or ArgumentType.NewId && a.Interface != null)
                {
                    RequireInterface(a.Interface);
                    types.Add(Naming.Pascal(a.Interface));
                }
                else
                {
                    types.Add("null");
                }
            }

            w.WriteLine($"new(\"{m.Name}\", \"{Signature(m)}\", [{string.Join(", ", types)}]),");
        }

        w.PopIndent();
        w.WriteLine("]" + end);
    }

    private static string Signature(Message m)
    {
        var builder = new StringBuilder();
        if (m.Since > 1)
        {
            builder.Append(m.Since);
        }

        foreach (var a in m.Arguments)
        {
            if (a.AllowNull)
            {
                builder.Append('?');
            }

            builder.Append(a.Type switch
            {
                ArgumentType.Int => "i",
                ArgumentType.Uint => "u",
                ArgumentType.Fixed => "f",
                ArgumentType.String => "s",
                ArgumentType.Object => "o",
                ArgumentType.NewId => a.Interface == null ? "sun" : "n",
                ArgumentType.Array => "a",
                ArgumentType.Fd => "h",
                _ => throw new ArgumentOutOfRangeException(),
            });
        }

        return builder.ToString();
    }

    private void Interface(TextGenerator w, Interface i)
    {
        var className = Naming.Pascal(i.Name);
        var names = new MemberNames(className, i);

        Summary(w, i.Summary);
        w.WriteLine($"public sealed unsafe partial class {className} : WaylandProxy, IWaylandInterface<{className}>");
        w.WriteOpenBraceAndIndent();
        w.WriteLine($"public const string InterfaceName = \"{i.Name}\";");
        w.WriteLine($"public const uint InterfaceVersion = {i.Version};");
        w.NewLine();
        w.WriteLine($"private {className}(nint handle, uint version) : base(handle, version)");
        w.WriteOpenBraceAndIndent();
        w.UnindentAndWriteCloseBrace();
        w.NewLine();
        w.WriteLine($"public static WlInterface* Interface => WaylandInterfaces.{className};");
        w.NewLine();
        w.WriteLine($"static {className} IWaylandInterface<{className}>.Create(nint handle, uint version) => new(handle, version);");

        foreach (var e in i.Enums)
        {
            w.NewLine();
            Enum(w, e);
        }

        for (var opcode = 0; opcode < i.Requests.Count; opcode++)
        {
            w.NewLine();
            Request(w, i, i.Requests[opcode], opcode, names.Requests[opcode]);
        }

        for (var opcode = 0; opcode < i.Events.Count; opcode++)
        {
            w.NewLine();
            EventDeclaration(w, i, i.Events[opcode], names.Events[opcode]);
        }

        w.NewLine();
        w.WriteLine("protected override void DispatchEvent(uint opcode, WlArgument* args)");
        w.WriteOpenBraceAndIndent();
        if (i.Events.Count > 0)
        {
            w.WriteLine("switch (opcode)");
            w.WriteOpenBraceAndIndent();
            for (var opcode = 0; opcode < i.Events.Count; opcode++)
            {
                w.WriteLine($"case {opcode}:");
                w.WriteOpenBraceAndIndent();
                EventDispatch(w, i, i.Events[opcode], names.Events[opcode]);
                w.WriteLine("break;");
                w.UnindentAndWriteCloseBrace();
            }

            w.UnindentAndWriteCloseBrace();
        }

        w.UnindentAndWriteCloseBrace();
        w.UnindentAndWriteCloseBrace();
    }

    private static void Enum(TextGenerator w, WaylandEnum e)
    {
        var name = Naming.Pascal(e.Name);
        Summary(w, e.Summary);
        if (e.IsBitfield)
        {
            w.WriteLine("[Flags]");
        }

        w.WriteLine($"public enum {name} : uint");
        w.WriteOpenBraceAndIndent();
        foreach (var entry in e.Entries)
        {
            Summary(w, entry.Summary);
            w.WriteLine($"{Naming.Pascal(entry.Name, name)} = {entry.Value},");
        }

        w.UnindentAndWriteCloseBrace();
    }

    private void Request(TextGenerator w, Interface i, Message m, int opcode, string name)
    {
        var newId = m.NewId;
        var untyped = m.HasUntypedNewId;
        var parameters = m.Arguments.Where(a => a.Type != ArgumentType.NewId)
            .Select(a => $"{RequestType(i, a)} {Naming.Camel(a.Name)}").ToList();

        string returnType;
        if (untyped)
        {
            if (m.Arguments.Any(a => Naming.Camel(a.Name) == "version"))
            {
                throw new InvalidDataException($"{i.Name}.{m.Name}: an argument named version meets the bound version");
            }

            parameters.Add("uint version");
            returnType = "T";
        }
        else if (newId != null)
        {
            RequireInterface(newId.Interface!);
            returnType = Naming.Pascal(newId.Interface!);
        }
        else
        {
            returnType = "void";
        }

        Summary(w, m.Summary);
        var generic = untyped ? "<T>" : "";
        w.WriteLine($"public {returnType} {name}{generic}({string.Join(", ", parameters)})");
        if (untyped)
        {
            w.PushIndent();
            w.WriteLine("where T : WaylandProxy, IWaylandInterface<T>");
            w.PopIndent();
        }

        w.WriteOpenBraceAndIndent();

        var slots = m.Arguments.Sum(a => a.Type == ArgumentType.NewId && a.Interface == null ? 3 : 1);

        var closers = 0;
        foreach (var a in m.Arguments)
        {
            var arg = Naming.Camel(a.Name);
            if (a.Type == ArgumentType.String)
            {
                w.WriteLine($"using var {Naming.Local(arg, "Utf8")} = new WaylandString({arg});");
            }
            else if (a.Type == ArgumentType.Array)
            {
                w.WriteLine($"fixed (byte* {Naming.Local(arg, "Data")} = {arg})");
                w.WriteOpenBraceAndIndent();
                w.WriteLine($"var {Naming.Local(arg, "Array")} = new WlArray({Naming.Local(arg, "Data")}, {arg}.Length);");
                closers++;
            }
        }

        w.WriteLine($"var wlArgs = stackalloc WlArgument[{Math.Max(slots, 1)}];");
        var slot = 0;
        foreach (var a in m.Arguments)
        {
            var arg = Naming.Camel(a.Name);
            switch (a.Type)
            {
                case ArgumentType.Int:
                    w.WriteLine($"wlArgs[{slot++}].i = {(a.Enum != null ? $"(int){arg}" : arg)};");
                    break;
                case ArgumentType.Uint:
                    w.WriteLine($"wlArgs[{slot++}].u = {(a.Enum != null ? $"(uint){arg}" : arg)};");
                    break;
                case ArgumentType.Fixed:
                    w.WriteLine($"wlArgs[{slot++}].f = WlFixed.FromDouble({arg});");
                    break;
                case ArgumentType.String:
                    w.WriteLine($"wlArgs[{slot++}].s = {Naming.Local(arg, "Utf8")}.Pointer;");
                    break;
                case ArgumentType.Object:
                    w.WriteLine(a.AllowNull
                        ? $"wlArgs[{slot++}].o = {arg}?.Handle ?? 0;"
                        : $"wlArgs[{slot++}].o = {arg}.Handle;");
                    break;
                case ArgumentType.NewId when a.Interface == null:
                    w.WriteLine($"wlArgs[{slot++}].s = T.Interface->name;");
                    w.WriteLine($"wlArgs[{slot++}].u = version;");
                    w.WriteLine($"wlArgs[{slot++}].n = 0;");
                    break;
                case ArgumentType.NewId:
                    w.WriteLine($"wlArgs[{slot++}].n = 0;");
                    break;
                case ArgumentType.Array:
                    w.WriteLine($"wlArgs[{slot++}].a = &{Naming.Local(arg, "Array")};");
                    break;
                case ArgumentType.Fd:
                    w.WriteLine($"wlArgs[{slot++}].h = {arg};");
                    break;
            }
        }

        if (untyped)
        {
            w.WriteLine($"return Create<T>(Marshal({opcode}, T.Interface, version, wlArgs), version);");
        }
        else if (newId != null)
        {
            w.WriteLine($"return Create<{returnType}>(Marshal({opcode}, {returnType}.Interface, Version, wlArgs), Version);");
        }
        else if (m.IsDestructor)
        {
            w.WriteLine($"MarshalDestroy({opcode}, wlArgs);");
        }
        else
        {
            w.WriteLine($"Marshal({opcode}, null, Version, wlArgs);");
        }

        for (var c = 0; c < closers; c++)
        {
            w.UnindentAndWriteCloseBrace();
        }

        w.UnindentAndWriteCloseBrace();
    }

    private void EventDeclaration(TextGenerator w, Interface i, Message m, string name)
    {
        var parameters = m.Arguments.Select(a => $"{EventType(i, a)} {Naming.Camel(a.Name)}");
        Summary(w, m.Summary);
        w.WriteLine($"public delegate void {name}Handler({string.Join(", ", parameters)});");
        w.NewLine();
        Summary(w, m.Summary);
        w.WriteLine($"public event {name}Handler {name};");
    }

    private void EventDispatch(TextGenerator w, Interface i, Message m, string name)
    {
        List<string> values = [];
        for (var index = 0; index < m.Arguments.Count; index++)
        {
            var a = m.Arguments[index];
            var arg = $"args[{index}]";
            switch (a.Type)
            {
                case ArgumentType.Int:
                    values.Add(a.Enum != null ? $"({EnumType(i, a.Enum)}){arg}.i" : $"{arg}.i");
                    break;
                case ArgumentType.Uint:
                    values.Add(a.Enum != null ? $"({EnumType(i, a.Enum)}){arg}.u" : $"{arg}.u");
                    break;
                case ArgumentType.Fixed:
                    values.Add($"WlFixed.ToDouble({arg}.f)");
                    break;
                case ArgumentType.String:
                    values.Add(a.AllowNull ? $"WaylandString.Read({arg}.s)" : $"WaylandString.Read({arg}.s) ?? string.Empty");
                    break;
                case ArgumentType.Object:
                    values.Add($"Find<{ObjectType(a)}>({arg}.o)");
                    break;
                case ArgumentType.NewId:
                    var local = Naming.Local(Naming.Camel(a.Name), "Created");
                    RequireInterface(a.Interface!);
                    w.WriteLine($"var {local} = Adopt<{Naming.Pascal(a.Interface!)}>({arg}.o, Version);");
                    values.Add(local);
                    break;
                case ArgumentType.Array:
                    values.Add($"{arg}.a->AsSpan()");
                    break;
                case ArgumentType.Fd:
                    values.Add($"{arg}.h");
                    break;
            }
        }

        w.WriteLine($"{name}?.Invoke({string.Join(", ", values)});");
        if (m.IsDestructor)
        {
            w.WriteLine("DestroyProxy();");
        }
    }

    private string RequestType(Interface i, Argument a)
    {
        return a.Type switch
        {
            ArgumentType.Int or ArgumentType.Uint when a.Enum != null => EnumType(i, a.Enum),
            ArgumentType.Int => "int",
            ArgumentType.Uint => "uint",
            ArgumentType.Fixed => "double",
            ArgumentType.String => "string",
            ArgumentType.Object => ObjectType(a),
            ArgumentType.Array => "ReadOnlySpan<byte>",
            ArgumentType.Fd => "int",
            _ => throw new ArgumentOutOfRangeException(),
        };
    }

    private string EventType(Interface i, Argument a)
    {
        return a.Type switch
        {
            ArgumentType.Int or ArgumentType.Uint when a.Enum != null => EnumType(i, a.Enum),
            ArgumentType.Int => "int",
            ArgumentType.Uint => "uint",
            ArgumentType.Fixed => "double",
            ArgumentType.String => "string",
            ArgumentType.Object => ObjectType(a),
            ArgumentType.NewId => Naming.Pascal(a.Interface!),
            ArgumentType.Array => "ReadOnlySpan<byte>",
            ArgumentType.Fd => "int",
            _ => throw new ArgumentOutOfRangeException(),
        };
    }

    private string ObjectType(Argument a)
    {
        if (a.Interface == null)
        {
            return "WaylandProxy";
        }

        RequireInterface(a.Interface);
        return Naming.Pascal(a.Interface);
    }

    private string EnumType(Interface i, string reference)
    {
        var dot = reference.IndexOf('.');
        var owner = dot < 0 ? i : interfaces.GetValueOrDefault(reference[..dot]);
        var name = dot < 0 ? reference : reference[(dot + 1)..];

        if (owner == null || owner.Enums.All(e => e.Name != name))
        {
            throw new InvalidDataException($"{i.Name}: enum '{reference}' is not in the protocols read");
        }

        var enumName = Naming.Pascal(name);
        return owner == i ? enumName : $"{Naming.Pascal(owner.Name)}.{enumName}";
    }

    private void RequireInterface(string name)
    {
        if (!interfaces.ContainsKey(name))
        {
            throw new InvalidDataException($"Interface '{name}' is referred to but not in the protocols read");
        }
    }

    private static void Summary(TextGenerator w, string summary)
    {
        if (string.IsNullOrWhiteSpace(summary))
        {
            return;
        }

        var text = SecurityElement.Escape(summary.Trim());
        w.WriteLine($"/// <summary>{char.ToUpperInvariant(text[0])}{text[1..]}</summary>");
    }

    private static IEnumerable<string> Dedent(string text)
    {
        var lines = text.Replace("\r", "").Split('\n').Select(l => l.TrimEnd()).ToList();
        while (lines.Count > 0 && lines[0].Length == 0)
        {
            lines.RemoveAt(0);
        }

        while (lines.Count > 0 && lines[^1].Length == 0)
        {
            lines.RemoveAt(lines.Count - 1);
        }
        var indent = lines.Where(l => l.Length > 0).Select(l => l.Length - l.TrimStart().Length).DefaultIfEmpty(0).Min();
        return lines.Select(l => l.Length >= indent ? l[indent..] : l);
    }

    private sealed class MemberNames
    {
        public MemberNames(string className, Interface i)
        {
            var taken = new HashSet<string>(BaseMembers) { className };
            foreach (var e in i.Enums)
            {
                taken.Add(Naming.Pascal(e.Name));
            }

            Requests = i.Requests.Select(r => Claim(taken, Naming.Pascal(r.Name), "Request")).ToList();
            Events = i.Events.Select(e => Claim(taken, Naming.Pascal(e.Name), "Event")).ToList();

            foreach (var e in Events)
            {
                if (!taken.Add(e + "Handler"))
                {
                    throw new InvalidDataException($"{i.Name}: {e}Handler is taken");
                }
            }
        }

        public IReadOnlyList<string> Requests { get; }

        public IReadOnlyList<string> Events { get; }

        private static string Claim(HashSet<string> taken, string name, string suffix)
        {
            var claimed = taken.Contains(name) ? name + suffix : name;
            if (!taken.Add(claimed))
            {
                throw new InvalidDataException($"Member name '{claimed}' is taken twice");
            }

            return claimed;
        }
    }
}
