        //Builds an object's transform from a visual-scene node, whichever form the node uses
        internal MatrixParams GetObjectMatrix(node node)
        {
            bool matrixTransposeNeeded = config.MatrixTransposeNeeded;
            bool singleMatrixPresent = false;
            var parameters = new MatrixParams();
            Matrix4x4F result = Matrix4x4F.Identity;
            if (node.Items == null)
            {
                return parameters;
            }

            foreach (Matrix4x4F meshMatrix in node.Items.OfType<matrix>().Select(matr => new Matrix4x4F(Array.ConvertAll(matr.Values, x => (float)x))))
            {
                if (matrixTransposeNeeded)
                {
                    meshMatrix.Transpose();
                }
                result = meshMatrix;
                singleMatrixPresent = true;
                break;
            }
            if (!singleMatrixPresent)
            {
                Vector3F translation = Vector3F.Zero;
                Vector3F scale = Vector3F.One;
                float rotationX = 0;
                float rotationY = 0;
                float rotationZ = 0;

                foreach (var item in node.Items)
                {
                    if (item is TargetableFloat3)
                    {
                        TargetableFloat3 target = item as TargetableFloat3;
                        var values = COLLADA.ConvertToFloatArray(target._Text_);
                        switch (target.sid)
                        {
                            case "scale":
                                scale = new Vector3F(values);
                                break;
                            default:
                                translation = new Vector3F(values);
                                break;
                        }
                    }
                    else if (item is rotate)
                    {
                        rotate rotate = item as rotate;
                        switch (rotate.sid)
                        {
                            case "rotationX":
                            case "rotateX":
                                rotationX = float.DegreesToRadians((float)rotate.Values[rotate.Values.Length - 1]);
                                break;
                            case "rotationY":
                            case "rotateY":
                                rotationY = float.DegreesToRadians((float)rotate.Values[rotate.Values.Length - 1]);
                                break;
                            case "rotationZ":
                            case "rotateZ":
                                rotationZ = float.DegreesToRadians((float)rotate.Values[rotate.Values.Length - 1]);
                                break;
                        }
                    }
                }
                parameters.Scale = scale;
                parameters.Translation = translation;
                parameters.Rotation = Quaternion.CreateFromYawPitchRoll<float>(rotationY, rotationX, rotationZ);

                return parameters;
                //result = Matrix4x4F.Scaling(scale) * Matrix4x4F.RotationX(rotationX) * Matrix4x4F.RotationX(rotationY) * Matrix4x4F.RotationX(rotationZ) *
                //                 Matrix4x4F.Translation(translation);

            }
            //AssembleModel changes the coordinate system - meshes, nodes, bones and key frames at once. Here it was
            //changed for Z_UP only, and only in the single-matrix branch: a component-wise pose was never converted.
            result.Decompose(out parameters.Scale, out parameters.Rotation, out parameters.Translation);
            return parameters;
        }

        //Get hierarchy from Visual scenes node
        public void GetMeshStructure(SceneData dataContainer, visual_scene visualScene, List<geometry> geometries,
           List<controller> controllers)
        {
            if (visualScene == null)
            {
                return;
            }

            Dictionary<node, SceneData.Model> nodeToMesh = new Dictionary<node, SceneData.Model>();
            foreach (var node in visualScene.node)
            {
                if (node == null)
                {
                    continue;
                }

                var queue = new Queue<node>();
                queue.Enqueue(node);
                while (queue.Count > 0)
                {
                    var currentNode = queue.Dequeue();
                    GetLightsAndCameraTranformation(dataContainer, currentNode);

                    var mesh = GetMeshStructure(dataContainer, currentNode, nodeToMesh, geometries, controllers);
                    if (currentNode.node1 != null)
                    {
                        foreach (var node1 in currentNode.node1)
                        {
                            queue.Enqueue(node1);
                            if (mesh != null)
                            {
                                nodeToMesh.Add(node1, mesh);
                            }
                        }
                    }
                }
            }

            RemoveDeadEndMeshes(dataContainer);
        }

        private void RemoveDeadEndMeshes(SceneData model)
        {
            if (model.Models != null)
            {
                Prune(model, model.Models);
            }
        }

        private bool Prune(SceneData model, SceneData.Model branch)
        {
            var kept = carriers.Contains(branch);
            for (var i = branch.Dependencies.Count - 1; i >= 0; i--)
            {
                var child = branch.Dependencies[i];
                if (Prune(model, child))
                {
                    kept = true;
                }
                else
                {
                    model.RemoveMesh(child);
                }
            }

            return kept;
        }

        private SceneData.Model GetMeshStructure(SceneData model, node rootNode, Dictionary<node, SceneData.Model> nodeToMesh, List<geometry> geometries, List<controller> controllers)
        {
            var id = IdOf(rootNode);
            var isJoint = rootNode.type == NodeType.JOINT;
            if (!isJoint && (rootNode.instance_camera != null || rootNode.instance_light != null))
            {
                return null;
            }

            var geometryId = GeometryOf(rootNode, geometries, controllers);
            if (!isJoint && geometryId == null && rootNode.node1 == null)
            {
                return null;
            }

            var created = CreateNode(model, rootNode, nodeToMesh, id);
            if (isJoint || geometryId != null)
            {
                carriers.Add(created);
            }

            if (geometryId != null)
            {
                var binding = rootNode.instance_geometry?[0].bind_material ?? rootNode.instance_controller?[0].bind_material;
                uses.Add(new GeometryUse(created, geometryId, binding));
            }

            return created;
        }

        /// <summary>The ID a node is known by in the model, its own: <see cref="NodeId"/> while no other node has it -
        /// a name repeats, an id does not - else that with a number after it, as a node nothing names gets.</summary>
        public String IdOf(node node)
        {
            if (ids.TryGetValue(node, out var id))
            {
                return id;
            }

            var named = NodeId(node);
            id = !String.IsNullOrEmpty(named) && takenIds.Add(named) ? named : $"{named}#{++unnamedNodes}";
            takenIds.Add(id);
            ids[node] = id;
            return id;
        }

