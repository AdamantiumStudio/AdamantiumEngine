using System.Security;
using QuantumBinding.Generator;
using QuantumBinding.Generator.AST;
using QuantumBinding.Generator.CodeGeneration;

namespace Adamantium.BindingGenerator.Wayland.CodeGeneration;

/// <summary>What the Wayland files have in common: the header, the summaries, and the interfaces of every protocol
/// read, which a protocol may refer to across files.</summary>
public abstract class WaylandCodeGenerator : CodeGenerator
{
    protected const string Namespace = "Adamantium.Wayland";

    protected WaylandCodeGenerator(ProcessingContext context, TranslationUnit[] units, IReadOnlyList<Protocol> protocols)
        : base(context, units, GeneratorCategory.Undefined)
    {
        Protocols = protocols;
        Interfaces = protocols.SelectMany(p => p.Interfaces).ToDictionary(i => i.Name);
    }

    protected IReadOnlyList<Protocol> Protocols { get; }

    protected IReadOnlyDictionary<string, Interface> Interfaces { get; }

    public override string FolderName => string.Empty;

    public override void Run(Declaration declaration)
    {
        throw new NotSupportedException("The Wayland files are written from the protocols, not per declaration.");
    }

    protected void Header(string source, string copyright)
    {
        WriteLine("// ----------------------------------------------------------------------------------------------");
        WriteLine("// <auto-generated>");
        WriteLine("// This file was generated by Adamantium.BindingGenerator" + (source == null ? "." : $" from {source}."));
        WriteLine("// Do not edit this file manually because you will lose all your changes after the next generation.");
        WriteLine("// </auto-generated>");
        WriteLine("// ----------------------------------------------------------------------------------------------");

        if (!string.IsNullOrWhiteSpace(copyright))
        {
            WriteLine("//");
            WriteLine("// The protocol it is generated from, and the documentation taken from it:");
            WriteLine("//");
            foreach (var line in Dedent(copyright))
            {
                WriteLine(line.Length == 0 ? "//" : "// " + line);
            }
        }

        NewLine();
    }

    protected void Summary(string summary)
    {
        if (string.IsNullOrWhiteSpace(summary))
        {
            return;
        }

        var text = SecurityElement.Escape(summary.Trim());
        WriteLine($"/// <summary>{char.ToUpperInvariant(text[0])}{text[1..]}</summary>");
    }

    protected void RequireInterface(string name)
    {
        if (!Interfaces.ContainsKey(name))
        {
            throw new InvalidDataException($"Interface '{name}' is referred to but not in the protocols read");
        }
    }

    private static IEnumerable<string> Dedent(string text)
    {
        var lines = text.Replace("\r", "").Split('\n').Select(l => l.TrimEnd()).ToList();
        while (lines.Count > 0 && lines[0].Length == 0)
        {
            lines.RemoveAt(0);
        }

        while (lines.Count > 0 && lines[^1].Length == 0)
        {
            lines.RemoveAt(lines.Count - 1);
        }

        var indent = lines.Where(l => l.Length > 0).Select(l => l.Length - l.TrimStart().Length).DefaultIfEmpty(0).Min();
        return lines.Select(l => l.Length >= indent ? l[indent..] : l);
    }
}
